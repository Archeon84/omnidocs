@OptIn(ExperimentalMaterial3Api::class)
@Composable
fun LocalChatScreen(
    onNavigateBack: () -> Unit,
    viewModel: LocalChatViewModel = hiltViewModel()
) {
    val context = LocalContext.current
    val scope = rememberCoroutineScope()
    val focusManager = LocalFocusManager.current
    val listState = rememberLazyListState()

    val sessions by viewModel.sessions.collectAsState()
    val currentSession by viewModel.currentSession.collectAsState()
    val messages by viewModel.messages.collectAsState()
    val isGenerating by viewModel.isGenerating.collectAsState()
    val streamingText by viewModel.streamingText.collectAsState()
    val activeModel by viewModel.activeModel.collectAsState()
    val isDeviceWarm by viewModel.isDeviceWarm.collectAsState()
    val tokensGenerated by viewModel.tokensGenerated.collectAsState()
    val tokensPerSecond by viewModel.tokensPerSecond.collectAsState()
    val snackbarHostState = remember { SnackbarHostState() }

    var inputText by remember { mutableStateOf("") }
    var showHistorySheet by remember { mutableStateOf(false) }
    var showTuningSheet by remember { mutableStateOf(false) }
    var showOfflineDialog by remember { mutableStateOf(false) }
    var editingMessage by remember { mutableStateOf<LocalChatMessage?>(null) }
    var renameSessionTarget by remember { mutableStateOf<LocalChatSession?>(null) }
    var renameTitleInput by remember { mutableStateOf("") }

    // Collect snackbar events
    LaunchedEffect(Unit) {
        viewModel.snackbarEvent.collect { message ->
            snackbarHostState.showSnackbar(message, duration = SnackbarDuration.Short)
        }
    }

    // Auto-scroll when messages or streaming text changes
    val isScrolledToBottom by remember {
        derivedStateOf {
            val totalItems = listState.layoutInfo.totalItemsCount
            if (totalItems == 0) true
            else {
                val lastVisible = listState.layoutInfo.visibleItemsInfo.lastOrNull()?.index ?: 0
                lastVisible >= totalItems - 2
            }
        }
    }

    LaunchedEffect(messages.size, streamingText.length) {
        if (isScrolledToBottom) {
            val target = messages.size - 1 + (if (isGenerating) 1 else 0)
            if (target >= 0) {
                listState.animateScrollToItem(target)
            }
        }
    }

    // Speech-to-Text launcher for offline voice dictation
    val speechLauncher = rememberLauncherForActivityResult(
        contract = ActivityResultContracts.StartActivityForResult()
    ) { result ->
        if (result.resultCode == Activity.RESULT_OK) {
            val matches = result.data?.getStringArrayListExtra(RecognizerIntent.EXTRA_RESULTS)
            val spokenText = matches?.firstOrNull()
            if (!spokenText.isNullOrBlank()) {
                inputText = if (inputText.isBlank()) spokenText else "$inputText $spokenText"
            }
        }
    }

    Scaffold(
        snackbarHost = { SnackbarHost(snackbarHostState) },
        topBar = {
            TopAppBar(
                title = {
                    Column {
                        Row(verticalAlignment = Alignment.CenterVertically) {
                            Text(
                                text = "Offline LLM",
                                style = MaterialTheme.typography.titleMedium,
                                fontWeight = FontWeight.Bold
                            )
                            Spacer(Modifier.width(8.dp))
                            Surface(
                                shape = RoundedCornerShape(12.dp),
                                color = MaterialTheme.colorScheme.primaryContainer.copy(alpha = 0.7f),
                                modifier = Modifier.clickable { showOfflineDialog = true }
                            ) {
                                Row(
                                    modifier = Modifier.padding(horizontal = 6.dp, vertical = 2.dp),
                                    verticalAlignment = Alignment.CenterVertically
                                ) {
                                    Icon(
                                        imageVector = Icons.Default.Shield,
                                        contentDescription = "Air-gapped",
                                        tint = MaterialTheme.colorScheme.primary,
                                        modifier = Modifier.size(12.dp)
                                    )
                                    Spacer(Modifier.width(4.dp))
                                    Text(
                                        text = "100% Offline",
                                        style = MaterialTheme.typography.labelSmall,
                                        fontSize = 10.sp,
                                        fontWeight = FontWeight.SemiBold,
                                        color = MaterialTheme.colorScheme.onPrimaryContainer
                                    )
                                }
                            }
                        }
                        Text(
                            text = activeModel?.name ?: "No local model loaded",
                            style = MaterialTheme.typography.bodySmall,
                            color = MaterialTheme.colorScheme.onSurfaceVariant,
                            maxLines = 1,
                            overflow = TextOverflow.Ellipsis
                        )
                    }
                },
                navigationIcon = {
                    IconButton(onClick = onNavigateBack) {
                        Icon(Icons.AutoMirrored.Filled.ArrowBack, contentDescription = "Back")
                    }
                },
                actions = {
                    IconButton(onClick = { showTuningSheet = true }) {
                        Icon(Icons.Default.Tune, contentDescription = "Inference & Persona")
                    }
                    IconButton(onClick = { showHistorySheet = true }) {
                        Icon(Icons.Outlined.Forum, contentDescription = "Chat History")
                    }
                    IconButton(onClick = { viewModel.createNewSession() }) {
                        Icon(Icons.Default.Add, contentDescription = "New Chat")
                    }
                }
            )
        },
        floatingActionButton = {
            AnimatedVisibility(
                visible = !isScrolledToBottom && (messages.isNotEmpty() || isGenerating),
                enter = fadeIn() + scaleIn(),
                exit = fadeOut() + scaleOut()
            ) {
                SmallFloatingActionButton(
                    onClick = {
                        scope.launch {
                            val target = messages.size - 1 + (if (isGenerating) 1 else 0)
                            if (target >= 0) listState.animateScrollToItem(target)
                        }
                    },
                    containerColor = MaterialTheme.colorScheme.secondaryContainer,
                    contentColor = MaterialTheme.colorScheme.onSecondaryContainer,
                    shape = CircleShape
                ) {
                    Box(contentAlignment = Alignment.Center) {
                        Icon(Icons.Default.KeyboardArrowDown, contentDescription = "Scroll to bottom")
                        if (isGenerating) {
                            Box(
                                modifier = Modifier
                                    .size(6.dp)
                                    .align(Alignment.TopEnd)
                                    .background(MaterialTheme.colorScheme.primary, CircleShape)
                            )
                        }
                    }
                }
            }
        }
    ) { paddingValues ->
        Column(
            modifier = Modifier
                .fillMaxSize()
                .padding(paddingValues)
                .imePadding()
        ) {
            // Warm device notice
            if (isDeviceWarm) {
                Surface(
                    color = MaterialTheme.colorScheme.errorContainer.copy(alpha = 0.7f),
                    modifier = Modifier.fillMaxWidth()
                ) {
                    Row(
                        modifier = Modifier.padding(horizontal = 16.dp, vertical = 6.dp),
                        verticalAlignment = Alignment.CenterVertically
                    ) {
                        Icon(
                            Icons.Default.Warning,
                            contentDescription = null,
                            tint = MaterialTheme.colorScheme.error,
                            modifier = Modifier.size(16.dp)
                        )
                        Spacer(Modifier.width(8.dp))
                        Text(
                            text = "Device is warm: local generation may throttled for safety",
                            style = MaterialTheme.typography.labelSmall,
                            color = MaterialTheme.colorScheme.onErrorContainer
                        )
                    }
                }
            }

            // Chat body: Empty state or message list
            if (messages.isEmpty() && !isGenerating) {
                LocalChatEmptyState(
                    activeModelName = activeModel?.name,
                    currentSession = currentSession,
                    onSuggestionClick = { suggestion ->
                        viewModel.sendMessage(suggestion)
                    },
                    modifier = Modifier
                        .weight(1f)
                        .fillMaxWidth()
                )
            } else {
                LazyColumn(
                    state = listState,
                    modifier = Modifier
                        .weight(1f)
                        .fillMaxWidth(),
                    contentPadding = PaddingValues(horizontal = 16.dp, vertical = 12.dp),
                    verticalArrangement = Arrangement.spacedBy(16.dp)
                ) {
                    items(messages, key = { it.id }) { msg ->
                        if (msg.role == "user") {
                            UserMessageBubble(
                                message = msg,
                                onCopy = { viewModel.copyToClipboard(context, msg.content) },
                                onEdit = { editingMessage = msg },
                                onDelete = { viewModel.deleteMessage(msg.id) }
                            )
                        } else {
                            val isLast = messages.indexOf(msg) == messages.size - 1
                            AssistantMessageCard(
                                message = msg,
                                isLast = isLast,
                                onCopy = { viewModel.copyToClipboard(context, msg.content) },
                                onRegenerate = { viewModel.regenerateLast() },
                                onDelete = { viewModel.deleteMessage(msg.id) },
                                onShare = {
                                    val sendIntent = Intent().apply {
                                        action = Intent.ACTION_SEND
                                        putExtra(Intent.EXTRA_TEXT, msg.content)
                                        type = "text/plain"
                                    }
                                    context.startActivity(Intent.createChooser(sendIntent, "Share AI Response"))
                                }
                            )
                        }
                    }

                    // Live streaming card
                    if (isGenerating) {
                        item(key = "streaming_card") {
                            LiveStreamingCard(
                                streamingText = streamingText,
                                modelName = activeModel?.name ?: "Local LLM",
                                tokensGenerated = tokensGenerated,
                                tokensPerSecond = tokensPerSecond,
                                onStop = { viewModel.stopGeneration() }
                            )
                        }
                    }
                }
            }

            // Input bar
            ChatInputBar(
                inputText = inputText,
                onInputChanged = { inputText = it },
                isGenerating = isGenerating,
                onSend = {
                    if (inputText.isNotBlank() && !isGenerating) {
                        viewModel.sendMessage(inputText)
                        inputText = ""
                        focusManager.clearFocus()
                    }
                },
                onStop = { viewModel.stopGeneration() },
                onMicClick = {
                    try {
                        val intent = Intent(RecognizerIntent.ACTION_RECOGNIZE_SPEECH).apply {
                            putExtra(RecognizerIntent.EXTRA_LANGUAGE_MODEL, RecognizerIntent.LANGUAGE_MODEL_FREE_FORM)
                            putExtra(RecognizerIntent.EXTRA_PROMPT, "Speak your prompt...")
                        }
                        speechLauncher.launch(intent)
                    } catch (_: Exception) {}
                }
            )
        }
    }

    // Persona & Tuning Sheet
    if (showTuningSheet) {
        InferenceTuningSheet(
            session = currentSession,
            onDismiss = { showTuningSheet = false },
            onPersonaSelected = { persona ->
                viewModel.updatePersona(persona)
            },
            onCustomPromptChanged = { prompt ->
                viewModel.updateCustomSystemPrompt(prompt)
            },
            onParametersChanged = { temp, topP, maxTokens ->
                viewModel.updateInferenceParameters(temp, topP, maxTokens)
            }
        )
    }

    // Chat History Sheet
    if (showHistorySheet) {
        ChatHistorySheet(
            sessions = sessions,
            currentSessionId = currentSession?.id,
            onDismiss = { showHistorySheet = false },
            onSelectSession = { id ->
                viewModel.selectSession(id)
                showHistorySheet = false
            },
            onNewChat = {
                viewModel.createNewSession()
                showHistorySheet = false
            },
            onRename = { session ->
                renameSessionTarget = session
                renameTitleInput = session.title
            },
            onDelete = { id ->
                viewModel.deleteSession(id)
            },
            onClearAll = {
                viewModel.clearCurrentSession()
                showHistorySheet = false
            }
        )
    }

    // Offline & Air-gap dialog
    if (showOfflineDialog) {
        AirtightOfflineDialog(
            modelName = activeModel?.name,
            onDismiss = { showOfflineDialog = false }
        )
    }

    // Edit message dialog
    editingMessage?.let { msg ->
        var editedText by remember { mutableStateOf(msg.content) }
        AlertDialog(
            onDismissRequest = { editingMessage = null },
            title = { Text("Edit Message") },
            text = {
                OutlinedTextField(
                    value = editedText,
                    onValueChange = { editedText = it },
                    modifier = Modifier.fillMaxWidth(),
                    minLines = 3,
                    maxLines = 6
                )
            },
            confirmButton = {
                Button(
                    onClick = {
                        val target = editingMessage
                        editingMessage = null
                        if (target != null && editedText.isNotBlank()) {
                            viewModel.editMessageAndResend(target.id, editedText)
                        }
                    }
                ) {
                    Text("Save & Resend")
                }
            },
            dismissButton = {
                TextButton(onClick = { editingMessage = null }) {
                    Text("Cancel")
                }
            }
        )
    }

    // Rename session dialog
    renameSessionTarget?.let { session ->
        AlertDialog(
            onDismissRequest = { renameSessionTarget = null },
            title = { Text("Rename Chat") },
            text = {
                OutlinedTextField(
                    value = renameTitleInput,
                    onValueChange = { renameTitleInput = it },
                    singleLine = true,
                    modifier = Modifier.fillMaxWidth()
                )
            },
            confirmButton = {
                Button(
                    onClick = {
                        viewModel.renameSession(session.id, renameTitleInput)
                        renameSessionTarget = null
                    }
                ) {
                    Text("Rename")
                }
            },
            dismissButton = {
                TextButton(onClick = { renameSessionTarget = null }) {
                    Text("Cancel")
                }
            }
        )
    }
}

